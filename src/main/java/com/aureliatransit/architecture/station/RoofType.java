package com.aureliatransit.architecture.station;

/**
 * Roof over the station.
 */
public enum RoofType {
	/** Open platforms, with lamps on the platform. */
	NONE,
	/** A flat canopy over each platform only, on columns along the platform. */
	CANOPY,
	/** One roof over the whole station (platforms and tracks), on beams carried by platform columns. */
	HALL
}
